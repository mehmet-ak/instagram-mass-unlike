#!/usr/bin/env sh
# Builds everything for Linux in ONE step. Run from the repository root with your
# virtual environment active:   sh build_linux.sh [version]
#
# Produces, in dist/:
#   instagram-mass-unlike_<version>_<arch>.deb   double-click install (Debian, Ubuntu, Mint...)
#   InstagramMassUnlike-Linux.tar.gz             for every other distribution
#   InstagramMassUnlike-LinuxGUI                 the bare executable (runs from anywhere)
# Upload the .deb and the .tar.gz to the GitHub Release. Users only download one of them.
set -eu

VERSION="${1:-1.1.0}"

pip install pyinstaller pillow

# The icon files are generated by assets/make_icon.py; recreate them if they are missing.
if [ ! -f assets/icon.png ] || [ ! -f assets/icon.ico ]; then
    python assets/make_icon.py
fi

pyinstaller --onefile --windowed --name InstagramMassUnlike-LinuxGUI \
    --add-data "assets/icon.png:assets" unlike_bot.py

# 1) .deb package
sh build_deb.sh "$VERSION"

# 2) tar.gz: executable + icon + menu installer, for non-Debian distributions
rm -rf build/tar
mkdir -p build/tar
cp dist/InstagramMassUnlike-LinuxGUI assets/icon.png install_linux.sh build/tar/
tar -czf dist/InstagramMassUnlike-Linux.tar.gz -C build/tar .

echo "Done. Release files are in dist/"
